#!/usr/bin/env node
// Generates the Dizzy CSS custom properties from src/dizzy/tokens.json.
//
// tokens.json is the design system's source of truth and is committed verbatim. Everything the
// stylesheets read — `var(--hotpink)`, `var(--space-5)`, `var(--shadow-sticker)` — comes from
// the two files this script writes, so the values can't drift from the token file the way a
// hand-copied variable block would:
//
//   src/dizzy/tokens.css          both themes as custom properties on <html>, keyed off
//                                 [data-theme], plus a prefers-color-scheme fallback for the
//                                 no-JS / nothing-stored case, and a print block that forces
//                                 daylight so dark-theme prints stay legible on white paper
//   src/dizzy/tailwind-theme.css  an `@theme inline` block aliasing every colour token as
//                                 `--color-<name>` so Tailwind utilities (bg-hotpink, text-ink)
//                                 resolve to the live token
//
// Only colours are aliased into Tailwind. Fonts, radii and shadows keep their token names
// (`--font-display`, `--radius-md`, …) because bundle.css reads exactly those, and a Tailwind
// theme variable of the same name would be self-referential. Layout comes from Tailwind; type,
// shape and colour come from the dz-*/iz-* classes.
//
// Usage: npm run dizzy:tokens   (src/dizzy/tokens.test.ts fails if the output is stale)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = resolve(here, '../src/dizzy/tokens.json');
export const TOKENS_CSS = resolve(here, '../src/dizzy/tokens.css');
export const THEME_CSS = resolve(here, '../src/dizzy/tailwind-theme.css');

// The fonts are self-hosted through fontsource, whose variable packages register the family as
// "<Name> Variable". Prepend that so the variable face is what actually loads; the token's own
// family name stays next in the stack as the fallback for anyone with the static font installed.
const SELF_HOSTED_FAMILY = {
  display: '"Baloo 2 Variable"',
  body: '"Space Grotesk Variable"',
};

const HEADER = `/* GENERATED by scripts/build-dizzy-tokens.mjs from src/dizzy/tokens.json — do not edit.
   Run \`npm run dizzy:tokens\` after changing the token file. */`;

const declare = (name, value) => `  --${name}: ${value};`;

/** Render both stylesheets from a parsed tokens.json. Pure, so the drift test can call it. */
export function render(tokens) {
  const [light, dark] = tokens.color.themes.map((theme) => theme.id);

  const themed = (theme) => [
    `  color-scheme: ${theme === light ? 'light' : 'dark'};`,
    ...tokens.color.tokens.map((token) => declare(token.name, token.value[theme])),
    ...tokens.shadow.tokens.map((token) => declare(token.name, token.value[theme])),
  ];

  // A media-scoped theme on every page not explicitly set to daylight: the OS-dark fallback and
  // the print override share this shape, so they can't drift apart.
  const override = (media, theme) => [
    `@media ${media} {`,
    `  :root:not([data-theme="${light}"]) {`,
    ...themed(theme).map((line) => `  ${line}`),
    '  }',
    '}',
  ];

  const fixed = [
    ...Object.entries(tokens.type.families).map(([role, stack]) =>
      declare(`font-${role}`, SELF_HOSTED_FAMILY[role] ? `${SELF_HOSTED_FAMILY[role]}, ${stack}` : stack)
    ),
    ...tokens.spacing.tokens.map((token) => declare(token.name, token.value)),
    ...tokens.radius.tokens.map((token) => declare(token.name, token.value)),
    ...tokens.stroke.tokens.map((token) => declare(token.name, token.value)),
  ];

  const tokensCss = [
    HEADER,
    '',
    `:root, [data-theme="${light}"] {`,
    ...themed(light),
    ...fixed,
    '}',
    '',
    `[data-theme="${dark}"] {`,
    ...themed(dark),
    '}',
    '',
    '/* Nothing stored and no script: follow the OS. ThemeBoot stamps data-theme when it runs, so',
    '   this only decides the first paint for no-JS visitors. */',
    ...override('(prefers-color-scheme: dark)', dark),
    '',
    '/* Paper is white: print in daylight whatever the screen theme. The selector covers both an',
    '   explicit afterglow and the OS-dark fallback, and outranks both by specificity and order. */',
    ...override('print', light),
    '',
  ].join('\n');

  const themeCss = [
    HEADER,
    '',
    '@theme inline {',
    ...tokens.color.tokens.map((token) => declare(`color-${token.name}`, `var(--${token.name})`)),
    '  --font-sans: var(--font-body);',
    '}',
    '',
  ].join('\n');

  return { tokensCss, themeCss };
}

export function build() {
  return render(JSON.parse(readFileSync(TOKENS_JSON, 'utf8')));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { tokensCss, themeCss } = build();
  writeFileSync(TOKENS_CSS, tokensCss);
  writeFileSync(THEME_CSS, themeCss);
  console.log(`✓ wrote ${TOKENS_CSS}\n✓ wrote ${THEME_CSS}`);
}
